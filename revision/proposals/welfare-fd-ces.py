#!/usr/bin/env python3
"""CORRECTED final-demand index (b) for the price-pinned matrix cells.

    python3 welfare-fd-ces.py        # writes welfare-fd-ces.md next to this file

SUPERSEDES the `(b)` column of `welfare-panel-v10.md`, which reported the VALUE
RATIO and labelled it a CES aggregate. The two are the same object only when the
basket grows proportionally. The c+g basket does not: private demand scales
roughly uniformly while the programme moves seven sectors only, so the bundle is
lopsided by construction and the value ratio is NOT a CES index.

What this script does, and its standing
---------------------------------------
It reconstructs the c+g basket from the CALIBRATION artifacts and the manifest
money-metrics. It is reproducible but PROVISIONAL: the authoritative
implementation belongs in the kernel (which holds data.gov_demand and the
programme bundle exactly). Assumptions, all explicit:

  private demand   c0_i = consumption_share_i * C0      (model-exact shares)
  public demand    g0_i = government_consumption_i / sum * G0
                         (IO composition, rescaled to the model's G0 --- the
                          weakest link in the chain)
  programme        prog_i = psi_2024_i * PG             (model-exact incidence)
  cell scaling     private demand scales by E1/E0, taken from the manifest
                   (exact); F1 additionally applies the preference shifter
                   d_F1_i and its normaliser sum(cs * d_F1).
  sectors with a zero baseline bundle are dropped (9 of 71), as the kernel's
  deflator does.

Indices reported
----------------
  value ratio   sum(f1)/sum(f0) - 1        what the old script computed
  CES s         [sum w0 (f1/f0)^((s-1)/s)]^(s/(s-1)),  w0 = f0/sum f0
  Tornqvist     exp( sum ((s1+w0)/2) log(f1/f0) ),  s1 = f1/sum f1
"""
import csv, os, tomllib
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
CAL = f"{REPO}/cbase2/data_processed"
RUNS = f"{REPO}/runs"
OUT = os.path.join(HERE, "welfare-fd-ces.md")

TG_BASE, E0, C0, G0, PG = 0.214101, 1.0 - 0.214101, 0.691675, 0.214101, 0.013310
SIGMAS = (0.5, 0.9, 1.0, 2.0)
CELLS = [("ALPHA", f) for f in ("F1", "F2", "F3")] + \
        [(c, f) for c in ("GAMMA", "DELTA") for f in ("F1", "F2", "F3")]


def load_basket():
    fc = list(csv.DictReader(open(f"{CAL}/financing_calibration.csv")))
    fd = list(csv.DictReader(open(f"{CAL}/AC_domestic_final_demand.csv")))
    cs = np.array([float(r["consumption_share"]) for r in fc])
    psi = np.array([float(r["psi_2024"]) for r in fc])
    dF1 = np.array([float(r["d_F1"]) for r in fc])
    gc = np.array([float(r["government_consumption"]) for r in fd])
    c0, g0 = cs * C0, gc / gc.sum() * G0
    k = (c0 + g0) > 0
    return c0[k], g0[k], psi[k], dF1[k], cs[k]


def ev_factor(cell):
    """E1/E0 for the cell, reconstructed from the manifest (exact)."""
    lab, fin = cell
    cid = f"matrix_5x3-v10-{lab}-{fin}" + ("-etas05" if lab == "BETA" else "")
    d = tomllib.load(open(f"{RUNS}/{cid}/manifest.toml", "rb"))
    m, g = d["metrics"], d["diagnostics"]
    F, Bg = m["external_transfer"], m.get("programme_financing", 0.0)
    E = m["nominal_gdp"] - g["gdp_g"] + F + (Bg if fin == "F3" else 0.0)
    return E / E0


def indices(f0, f1):
    w0 = f0 / f0.sum()
    r = f1 / f0
    out = [("value ratio", f1.sum() / f0.sum() - 1)]
    for s in SIGMAS:
        q = np.exp(w0 @ np.log(r)) if abs(s - 1) < 1e-12 else (w0 @ r ** ((s - 1) / s)) ** (s / (s - 1))
        out.append((f"CES {s}", float(q) - 1))
    s1 = f1 / f1.sum()
    out.append(("Tornqvist", float(np.exp(((s1 + w0) / 2) @ np.log(r))) - 1))
    return out


def build():
    c0, g0, psi, dF1, cs = load_basket()
    f0 = c0 + g0
    L = ["# Corrected final-demand index (b) --- CES aggregate, not the value ratio", "",
         "Generated by `welfare-fd-ces.py` from the calibration artifacts plus the manifest",
         "money-metrics. PROVISIONAL: reconstructs the basket, pending the kernel. In percent",
         "against the reference continuation; price-pinned cells only. The `value ratio` column is what",
         "`welfare-panel-v10.md` reported as `(b) c+g`.", "",
         f"Bundle: {len(f0)} sectors, private {c0.sum():.4f} + public {g0.sum():.4f}; "
         f"programme {100*PG/(C0+G0):.3f}% of the bundle; programme sectors hold "
         f"{100*(f0[psi>0].sum()/f0.sum()):.2f}% of it.", "",
         "| Cell | value ratio | " + " | ".join(f"CES {s}" for s in SIGMAS) +
         " | Tornqvist | old (b) | sign flip |",
         "| --- | ---: | " + " | ".join("---:" for _ in SIGMAS) + " | ---: | ---: | --- |"]
    for cell in CELLS:
        fac = ev_factor(cell)
        c1 = fac * c0 * (dF1 / (cs @ dF1) if cell[1] == "F1" else 1.0)
        g1 = g0 + (psi * PG if cell[1] != "F1" else 0.0)
        vals = indices(f0, c1 + g1)
        v = dict(vals)
        flip = "YES" if (v["value ratio"] > 0) != (v["CES 0.9"] > 0) else ""
        L.append(f"| `{cell[0]}-{cell[1]}` | " +
                 " | ".join(f"{100*x:+.4f}" for _, x in vals) +
                 f" | {flip} |")
    L += ["", "## Reading", "",
          "- The value ratio and the CES aggregate coincide only when every good grows",
          "  proportionally. The `c+g` basket does not, so they differ at first order in",
          "  the reallocation, and the difference can flip the sign.",
          "- `sigma < 1` makes the goods complements, which is exactly the regime that",
          "  penalises a lopsided basket; `sigma = 2` (substitutes) cuts the gap by an",
          "  order of magnitude, and `sigma` is therefore the *whole content* of this index",
          "  at pinned prices, not an irrelevance.",
          "- No deflator is involved anywhere: the CES aggregate is computed from the",
          "  basket directly. A deflator would only be needed for the separate",
          "  deflated-expenditure index.",
          "- Fixed-weight arithmetic indices (Laspeyres, Paasche) *do* equal the value",
          "  ratio at unchanged prices. Geometric and curvature-weighted indices do not.",
          "  That distinction is the whole of the correction."]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    open(OUT, "w").write(build())
    print("wrote", OUT)
